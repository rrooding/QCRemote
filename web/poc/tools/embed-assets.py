#!/usr/bin/env python3
"""Gzips the PoC's assets and, optionally, emits them as a C++ header.

This is the prototype of ADR 0011's asset pipeline, kept in the PoC so the
numbers in that ADR can be re-measured with one command:

    python3 web/poc/tools/embed-assets.py                 # size report
    python3 web/poc/tools/embed-assets.py --out /tmp/x.hpp # + the header

Python 3 standard library only, on purpose: `west` already requires Python, so
the firmware build can run this without adding a second toolchain. Nothing
here is firmware code and nothing in firmware/ references it yet - wiring it
into firmware/app/CMakeLists.txt is the implementation step, not this
research.

The gzip stream is written deterministically (mtime 0, no stored filename) so
a rebuild of unchanged assets produces byte-identical output - which is what
lets CI diff a generated header instead of trusting that someone remembered to
regenerate it.
"""

from __future__ import annotations

import argparse
import gzip
import io
import sys
from pathlib import Path

POC_ROOT = Path(__file__).resolve().parent.parent

# Served paths, in load order, with the Content-Type Zephyr's HTTP server
# would report for each. Listed explicitly rather than globbed: an asset that
# nothing references should not silently cost flash.
ASSETS: list[tuple[str, str]] = [
    ("/", "text/html"),
    ("/manifest.webmanifest", "application/manifest+json"),
    ("/src/main.js", "text/javascript"),
    ("/src/store.js", "text/javascript"),
    ("/src/store-controller.js", "text/javascript"),
    ("/src/qc-app.js", "text/javascript"),
    ("/src/qc-now-playing.js", "text/javascript"),
    ("/src/qc-preset-list.js", "text/javascript"),
    ("/src/qc-knob.js", "text/javascript"),
    ("/vendor/lit.js", "text/javascript"),
]


def source_path(served: str) -> Path:
    return POC_ROOT / ("index.html" if served == "/" else served.lstrip("/"))


def gzip_bytes(raw: bytes) -> bytes:
    buffer = io.BytesIO()
    # mtime=0 and filename=None keep the 10-byte header free of anything that
    # changes between builds.
    with gzip.GzipFile(fileobj=buffer, mode="wb", compresslevel=9, mtime=0) as handle:
        handle.write(raw)
    return buffer.getvalue()


def c_identifier(served: str) -> str:
    if served == "/":
        return "kIndexHtmlGz"
    stem = served.lstrip("/").replace("/", "_").replace("-", "_").replace(".", "_")
    return "k" + "".join(part.capitalize() for part in stem.split("_")) + "Gz"


def emit_header(entries: list[tuple[str, str, bytes]], out: Path) -> None:
    lines = [
        "#pragma once",
        "",
        "// Generated by web/poc/tools/embed-assets.py - do not edit.",
        "// Each payload is a complete gzip stream, served with",
        "// Content-Encoding: gzip (see ADR 0011).",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace qcbridge::webassets {",
        "",
    ]
    for served, _content_type, payload in entries:
        name = c_identifier(served)
        lines.append(f"// {served} ({len(payload)} B gzipped)")
        lines.append(f"inline constexpr uint8_t {name}[] = {{")
        for offset in range(0, len(payload), 16):
            chunk = payload[offset : offset + 16]
            lines.append("    " + "".join(f"0x{byte:02x}, " for byte in chunk).rstrip())
        lines.append("};")
        lines.append("")

    lines += [
        "struct Asset {",
        "    const char* path;",
        "    const char* contentType;",
        "    const uint8_t* gzipped;",
        "    size_t gzippedLength;",
        "};",
        "",
        "inline constexpr Asset kAssets[] = {",
    ]
    for served, content_type, payload in entries:
        name = c_identifier(served)
        lines.append(
            f'    {{"{served}", "{content_type}", {name}, sizeof({name})}},'
        )
    lines += [
        "};",
        "",
        "}  // namespace qcbridge::webassets",
        "",
    ]
    out.write_text("\n".join(lines))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, help="write a C++ header here as well")
    args = parser.parse_args()

    entries: list[tuple[str, str, bytes]] = []
    raw_total = 0
    gz_total = 0
    missing: list[str] = []

    for served, content_type in ASSETS:
        path = source_path(served)
        if not path.is_file():
            missing.append(str(path))
            continue
        raw = path.read_bytes()
        payload = gzip_bytes(raw)
        entries.append((served, content_type, payload))
        raw_total += len(raw)
        gz_total += len(payload)

    if missing:
        print("missing assets:\n  " + "\n  ".join(missing), file=sys.stderr)
        return 1

    width = max(len(served) for served, _, _ in entries)
    print(f"{'served path'.ljust(width)}  {'raw':>8}  {'gzip -9':>8}")
    for served, _content_type, payload in entries:
        raw_len = len(source_path(served).read_bytes())
        print(f"{served.ljust(width)}  {raw_len:>8}  {len(payload):>8}")
    print(f"{'TOTAL'.ljust(width)}  {raw_total:>8}  {gz_total:>8}")
    print(
        f"\n{len(entries)} assets, {gz_total} B gzipped "
        f"({gz_total / raw_total:.0%} of raw) - the flash cost of the whole UI."
    )

    if args.out:
        emit_header(entries, args.out)
        print(f"wrote {args.out} ({args.out.stat().st_size} B of C++)")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
