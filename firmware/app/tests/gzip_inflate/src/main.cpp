#include <zephyr/ztest.h>

#include "QcGzip.hpp"

using namespace qcbridge;

ZTEST_SUITE(gzip_inflate, NULL, NULL, NULL, NULL, NULL);

// One shared output buffer, not one per test: kMaxInflatedSize is 16KB,
// and a `static` *local* in each ZTEST function is still a distinct
// global each - four or five of those together overflowed
// qemu_cortex_m3's small RAM region at link time ("RAM overflow"),
// confirmed the hard way before consolidating to this single instance.
// Ztest runs this suite's cases sequentially on one thread, so reusing it
// across tests is safe.
static std::array<uint8_t, gzip::kMaxInflatedSize> gOutputBuffer{};

