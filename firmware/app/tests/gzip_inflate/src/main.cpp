// --- hasMagic() ---------------------------------------------------------

ZTEST(gzip_inflate, test_has_magic_true_for_gzip_prefix)
{
    zassert_true(gzip::hasMagic({kValidGzip.data(), kValidGzip.size()}), "expected magic");
}

ZTEST(gzip_inflate, test_has_magic_false_for_plain_protobuf)
{
    // Ordinary protobuf wire bytes (a varint field tag) - the generic
    // property this issue implements must leave these untouched.
    const std::vector<uint8_t> proto = {0x08, 0x01, 0x12, 0x02, 'h', 'i'};
    zassert_false(gzip::hasMagic({proto.data(), proto.size()}), "expected no magic");
}

ZTEST(gzip_inflate, test_has_magic_false_for_short_input)
{
    const std::vector<uint8_t> tooShort = {0x1f, 0x8b};
    zassert_false(gzip::hasMagic({tooShort.data(), tooShort.size()}), "expected false, not a crash");
    zassert_false(gzip::hasMagic({}), "empty input");
}

// --- inflate(): pass-through is the caller's job, not inflate()'s -----
// (QcSession::handleMessage() only calls inflate() after hasMagic() is
// true; uncompressed protoBytes are never passed to it at all. Covered
// at the hasMagic() level above.)

// --- inflate(): valid input ---------------------------------------------

ZTEST(gzip_inflate, test_inflate_valid_gzip_round_trips)
{
    const auto result =
        gzip::inflate({kValidGzip.data(), kValidGzip.size()}, {gOutputBuffer.data(), gOutputBuffer.size()});

    zassert_true(result.has_value(), "expected successful inflate");
    zassert_equal(result->size(), kPlaintext.size(), "decompressed size");
    zassert_mem_equal(result->data(), kPlaintext.data(), kPlaintext.size(), "decompressed bytes");
}

// --- inflate(): oversize output ------------------------------------------

ZTEST(gzip_inflate, test_inflate_output_too_large_fails_cleanly)
{
    std::array<uint8_t, 4> tinyOutput{};  // kPlaintext is 69 bytes - won't fit
    const auto result =
        gzip::inflate({kValidGzip.data(), kValidGzip.size()}, {tinyOutput.data(), tinyOutput.size()});

    zassert_false(result.has_value(), "expected failure, not a truncated/overflowed write");
    zassert_true(result.error() == gzip::InflateError::OutputTooLarge, "expected OutputTooLarge");
}

// --- inflate(): truncated input ------------------------------------------

ZTEST(gzip_inflate, test_inflate_truncated_input_fails_cleanly)
{
    const auto result = gzip::inflate({kTruncatedGzip.data(), kTruncatedGzip.size()},
                                       {gOutputBuffer.data(), gOutputBuffer.size()});

    zassert_false(result.has_value(), "expected failure");
    zassert_true(result.error() == gzip::InflateError::Truncated, "expected Truncated");
}

// --- inflate(): bad CRC ---------------------------------------------------

ZTEST(gzip_inflate, test_inflate_bad_crc_fails_cleanly)
{
    const auto result = gzip::inflate({kBadCrcGzip.data(), kBadCrcGzip.size()},
                                       {gOutputBuffer.data(), gOutputBuffer.size()});

    zassert_false(result.has_value(), "expected failure");
    zassert_true(result.error() == gzip::InflateError::CrcMismatch, "expected CrcMismatch");
}

// --- inflate(): false-positive magic prefix ------------------------------

ZTEST(gzip_inflate, test_inflate_false_positive_magic_fails_cleanly)
{
    const auto result = gzip::inflate({kFalsePositiveMagic.data(), kFalsePositiveMagic.size()},
                                       {gOutputBuffer.data(), gOutputBuffer.size()});

    zassert_false(result.has_value(), "expected failure, not a crash");
    zassert_true(result.error() == gzip::InflateError::HeaderMalformed, "expected HeaderMalformed");
}

ZTEST(gzip_inflate, test_inflate_rejects_input_without_magic)
{
    const std::vector<uint8_t> proto = {0x08, 0x01, 0x12, 0x02, 'h', 'i'};
    const auto result = gzip::inflate({proto.data(), proto.size()}, {gOutputBuffer.data(), gOutputBuffer.size()});

    zassert_false(result.has_value(), "expected failure");
    zassert_true(result.error() == gzip::InflateError::NotGzipped, "expected NotGzipped");
}
