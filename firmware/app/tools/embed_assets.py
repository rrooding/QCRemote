#!/usr/bin/env python3
"""Gzips web/ui's assets into a generated C++ header (issue #88, ADR 0011).

Adapted from web/poc/tools/embed-assets.py (that script's own research
prototype, which only emitted a size report and the raw byte arrays): this
one also emits, for each asset, the Zephyr `http_resource_detail_static` /
`HTTP_RESOURCE_DEFINE` pair that serves it from the board with
`Content-Encoding: gzip` - the actual firmware build step, wired into
firmware/app/CMakeLists.txt and firmware/app/tests/wifi_web_http/CMakeLists.txt
via firmware/app/cmake/EmbedWebAssets.cmake. Not meant to be run by hand in
normal use; CMake reruns it automatically whenever a file under web/ui
changes, which is what lets "add a UI file" need no firmware code change
beyond that directory.

    python3 firmware/app/tools/embed_assets.py --ui-dir web/ui --out /tmp/x.hpp

Python 3 standard library only, on purpose: `west` already requires Python,
so this adds no second toolchain to firmware CI (ADR 0011's "the firmware
build stays Python-only").

The gzip stream is written deterministically (mtime 0, no stored filename)
so a rebuild of unchanged assets produces byte-identical output.
"""

from __future__ import annotations

import argparse
import gzip
import io
from pathlib import Path

# Served paths, in load order, with the Content-Type Zephyr's HTTP server
# reports for each. Listed explicitly rather than globbed: an asset that
# nothing references should not silently cost flash (same reasoning as the
# PoC script this was adapted from).
ASSETS: list[tuple[str, str]] = [
    ("/", "text/html"),
    ("/manifest.webmanifest", "application/manifest+json"),
    ("/src/main.js", "text/javascript"),
    ("/src/store.js", "text/javascript"),
    ("/src/store-controller.js", "text/javascript"),
    ("/src/qc-app.js", "text/javascript"),
    ("/src/qc-status.js", "text/javascript"),
    ("/src/qc-preset-list.js", "text/javascript"),
    ("/vendor/lit.js", "text/javascript"),
]


def source_path(ui_dir: Path, served: str) -> Path:
    return ui_dir / ("index.html" if served == "/" else served.lstrip("/"))


def gzip_bytes(raw: bytes) -> bytes:
    buffer = io.BytesIO()
    # mtime=0 and filename=None keep the 10-byte header free of anything
    # that changes between builds.
    with gzip.GzipFile(fileobj=buffer, mode="wb", compresslevel=9, mtime=0) as handle:
        handle.write(raw)
    return buffer.getvalue()


def c_identifier(served: str) -> str:
    """A PascalCase identifier fragment unique per served path, e.g.
    "/src/qc-app.js" -> "SrcQcAppJs", "/" -> "Index"."""
    stem = "index" if served == "/" else served.lstrip("/")
    stem = stem.replace("/", "_").replace("-", "_").replace(".", "_")
    return "".join(part.capitalize() for part in stem.split("_"))


def emit_header(entries: list[tuple[str, str, bytes]], out: Path) -> None:
    lines = [
        "#pragma once",
        "",
        "// Generated by firmware/app/tools/embed_assets.py from web/ui - do",
        "// not edit by hand. Each payload is a complete gzip stream, served",
        "// with Content-Encoding: gzip as a Zephyr HTTP static resource",
        "// (issue #88, ADR 0011). Must be #included inside `namespace",
        "// qcbridge { ... }`, after qcWebService's own HTTP_SERVICE_DEFINE -",
        "// see QcWifiWebTransport.hpp, the only includer.",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace webassets {",
        "",
        "struct Asset {",
        "    const char* path;",
        "    const char* contentType;",
        "    const uint8_t* gzipped;",
        "    size_t gzippedLength;",
        "};",
        "",
    ]
    for served, _content_type, payload in entries:
        name = c_identifier(served)
        lines.append(f"// {served} ({len(payload)} B gzipped)")
        lines.append(f"inline constexpr uint8_t k{name}Gz[] = {{")
        for offset in range(0, len(payload), 16):
            chunk = payload[offset : offset + 16]
            lines.append("    " + "".join(f"0x{byte:02x}, " for byte in chunk).rstrip())
        lines.append("};")
        lines.append("")

    lines.append("inline constexpr Asset kAssets[] = {")
    for served, content_type, payload in entries:
        name = c_identifier(served)
        lines.append(f'    {{"{served}", "{content_type}", k{name}Gz, sizeof(k{name}Gz)}},')
    lines += ["};", "", "}  // namespace webassets", ""]

    for served, content_type, _payload in entries:
        name = c_identifier(served)
        lines += [
            f"inline http_resource_detail_static g_webAsset{name}ResourceDetail{{",
            "    .common = {",
            "        .bitmask_of_supported_http_methods = BIT(HTTP_GET),",
            "        .type = HTTP_RESOURCE_TYPE_STATIC,",
            '        .content_encoding = "gzip",',
            f'        .content_type = "{content_type}",',
            "    },",
            f"    .static_data = webassets::k{name}Gz,",
            f"    .static_data_len = sizeof(webassets::k{name}Gz),",
            "};",
            "",
        ]

    # Wrapped in extern "C", same reason QcWifiWebTransport.hpp's own
    # hand-written HTTP_SERVICE_DEFINE/HTTP_RESOURCE_DEFINE calls are: the
    # macros' STRUCT_SECTION_ITERABLE_ALTERNATE expansion declares extern
    # references to GNU ld's own plain-C section-boundary symbols, which a
    # default C++ (mangled) declaration inside a namespace would not match.
    lines.append('extern "C" {')
    for served, _content_type, _payload in entries:
        name = c_identifier(served)
        lines.append(
            f'HTTP_RESOURCE_DEFINE(qcWebAsset{name}Resource, qcWebService, "{served}", '
            f"&g_webAsset{name}ResourceDetail);"
        )
    lines += ["}", ""]

    out.write_text("\n".join(lines))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ui-dir", type=Path, required=True, help="path to web/ui")
    parser.add_argument("--out", type=Path, required=True, help="C++ header to write")
    args = parser.parse_args()

    entries: list[tuple[str, str, bytes]] = []
    missing: list[str] = []
    for served, content_type in ASSETS:
        path = source_path(args.ui_dir, served)
        if not path.is_file():
            missing.append(str(path))
            continue
        payload = gzip_bytes(path.read_bytes())
        entries.append((served, content_type, payload))

    if missing:
        raise SystemExit("missing web UI assets:\n  " + "\n  ".join(missing))

    width = max(len(served) for served, _, _ in entries)
    gz_total = sum(len(payload) for _, _, payload in entries)
    print(f"{'served path'.ljust(width)}  {'gzip -9':>8}")
    for served, _content_type, payload in entries:
        print(f"{served.ljust(width)}  {len(payload):>8}")
    print(f"{'TOTAL'.ljust(width)}  {gz_total:>8}")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    emit_header(entries, args.out)
    print(f"\nwrote {args.out} ({len(entries)} assets, {gz_total} B gzipped)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
