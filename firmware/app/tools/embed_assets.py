#!/usr/bin/env python3
"""Gzips web/ui's assets into a generated C++ header (issue #88, ADR 0011).

Adapted from web/poc/tools/embed-assets.py (that script's own research
prototype, which only emitted a size report and the raw byte arrays): this
one also emits, for each asset, the Zephyr `http_resource_detail_dynamic` /
`HTTP_RESOURCE_DEFINE` pair that serves it from the board (through
QcWifiWebTransport.hpp's serveWebAsset(), which adds `Content-Encoding: gzip`
and `Cache-Control: no-cache`) - the actual firmware build step, wired into
firmware/app/CMakeLists.txt and firmware/app/tests/wifi_web_http/CMakeLists.txt
via firmware/app/cmake/EmbedWebAssets.cmake. Not meant to be run by hand in
normal use; CMake reruns it automatically whenever a file under web/ui
changes, which is what lets "add a UI file" need no firmware code change
beyond that directory.

    python3 firmware/app/tools/embed_assets.py --ui-dir web/ui --out /tmp/x.hpp \
        --build-id-out /tmp/build_id.hpp

Issue #99: it also stamps the build id (the git commit, ADR 0012) into both
the page and the firmware, from one value: web/ui/src/build.js is checked in
as `export const BUILD = 'dev';` and served with the real id in its place, and
--build-id-out gets the same id as a C++ constant (`qcbridge::kBuildId`).
Both outputs are rewritten only when their content changes, so CMake can run
this on every build (to pick up a new commit) without recompiling anything.

Python 3 standard library only, on purpose: `west` already requires Python,
so this adds no second toolchain to firmware CI (ADR 0011's "the firmware
build stays Python-only").

The gzip stream is written deterministically (mtime 0, no stored filename)
so a rebuild of unchanged assets produces byte-identical output.
"""

from __future__ import annotations

import argparse
import gzip
import io
import re
import subprocess
from pathlib import Path

# Served paths, in load order, with the Content-Type Zephyr's HTTP server
# reports for each. Listed explicitly rather than globbed: an asset that
# nothing references should not silently cost flash (same reasoning as the
# PoC script this was adapted from).
ASSETS: list[tuple[str, str]] = [
    ("/", "text/html"),
    ("/manifest.webmanifest", "application/manifest+json"),
    ("/src/main.js", "text/javascript"),
    ("/src/build.js", "text/javascript"),
    ("/src/store.js", "text/javascript"),
    ("/src/store-controller.js", "text/javascript"),
    ("/src/qc-app.js", "text/javascript"),
    ("/src/qc-status.js", "text/javascript"),
    ("/src/qc-preset-list.js", "text/javascript"),
    ("/vendor/lit.js", "text/javascript"),
]


# web/ui/src/build.js, as checked in. The page imports BUILD from it; only
# the quoted value is replaced, keeping whichever quote the file uses (the
# web UI's own style is single quotes; double is accepted too).
BUILD_JS = "/src/build.js"
BUILD_JS_PATTERN = re.compile(r"""^(export const BUILD = (['"]))[^'"]*(\2;)$""", re.MULTILINE)

# docs/api/schema/server-message.schema.json's "build".
BUILD_ID_PATTERN = re.compile(r"^[0-9A-Za-z._+-]{1,40}$")


def git_build_id(repo: Path) -> str:
    """The short commit hash of HEAD, or "unknown" outside a usable git
    checkout (a source tarball, or a container that can't see .git).

    safe.directory: a CI container often runs as a different user than the
    one owning the bind-mounted checkout, and git then refuses to read it."""
    try:
        result = subprocess.run(
            ["git", "-c", "safe.directory=*", "-C", str(repo), "rev-parse", "--short=7", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return "unknown"
    return result.stdout.strip() or "unknown"


def stamp_build_js(raw: bytes, build_id: str) -> bytes:
    text = raw.decode("utf-8")
    stamped, count = BUILD_JS_PATTERN.subn(lambda m: f"{m.group(1)}{build_id}{m.group(3)}", text)
    if count != 1:
        raise SystemExit(f"{BUILD_JS} must contain exactly one line: export const BUILD = '...';")
    return stamped.encode("utf-8")


def write_if_changed(path: Path, text: str) -> None:
    if path.is_file() and path.read_text() == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def emit_build_id_header(build_id: str, out: Path) -> None:
    lines = [
        "#pragma once",
        "",
        "// Generated by firmware/app/tools/embed_assets.py - do not edit by hand.",
        "// The same id is stamped into the page's web/ui/src/build.js (issue #99).",
        "",
        "#include <string_view>",
        "",
        "namespace qcbridge {",
        f'inline constexpr std::string_view kBuildId = "{build_id}";',
        "}  // namespace qcbridge",
        "",
    ]
    write_if_changed(out, "\n".join(lines))


def source_path(ui_dir: Path, served: str) -> Path:
    return ui_dir / ("index.html" if served == "/" else served.lstrip("/"))


def gzip_bytes(raw: bytes) -> bytes:
    buffer = io.BytesIO()
    # mtime=0 and filename=None keep the 10-byte header free of anything
    # that changes between builds.
    with gzip.GzipFile(fileobj=buffer, mode="wb", compresslevel=9, mtime=0) as handle:
        handle.write(raw)
    return buffer.getvalue()


def c_identifier(served: str) -> str:
    """A PascalCase identifier fragment unique per served path, e.g.
    "/src/qc-app.js" -> "SrcQcAppJs", "/" -> "Index"."""
    stem = "index" if served == "/" else served.lstrip("/")
    stem = stem.replace("/", "_").replace("-", "_").replace(".", "_")
    return "".join(part.capitalize() for part in stem.split("_"))


def emit_header(entries: list[tuple[str, str, bytes]], out: Path) -> None:
    lines = [
        "#pragma once",
        "",
        "// Generated by firmware/app/tools/embed_assets.py from web/ui - do",
        "// not edit by hand. Each payload is a complete gzip stream, served by",
        "// serveWebAsset() as a Zephyr HTTP dynamic resource (issues #88, #99,",
        "// ADR 0011). Must be #included inside `namespace qcbridge { ... }`,",
        "// after qcWebService's own HTTP_SERVICE_DEFINE - see",
        "// QcWifiWebTransport.hpp, the only includer.",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace webassets {",
        "",
    ]
    for served, _content_type, payload in entries:
        name = c_identifier(served)
        lines.append(f"// {served} ({len(payload)} B gzipped)")
        lines.append(f"inline constexpr uint8_t k{name}Gz[] = {{")
        for offset in range(0, len(payload), 16):
            chunk = payload[offset : offset + 16]
            lines.append("    " + "".join(f"0x{byte:02x}, " for byte in chunk).rstrip())
        lines.append("};")
        lines.append("")

    lines.append("inline constexpr QcWebAsset kAssets[] = {")
    for served, content_type, payload in entries:
        name = c_identifier(served)
        lines.append(f'    {{"{served}", "{content_type}", k{name}Gz, sizeof(k{name}Gz)}},')
    lines += ["};", "", "}  // namespace webassets", ""]

    # user_data is a plain void* in Zephyr's struct; serveWebAsset() only
    # ever reads through it.
    for index, (served, content_type, _payload) in enumerate(entries):
        name = c_identifier(served)
        lines += [
            f"inline http_resource_detail_dynamic g_webAsset{name}ResourceDetail{{",
            "    .common = {",
            "        .bitmask_of_supported_http_methods = BIT(HTTP_GET),",
            "        .type = HTTP_RESOURCE_TYPE_DYNAMIC,",
            "        .content_encoding = nullptr,",
            f'        .content_type = "{content_type}",',
            "    },",
            "    .cb = &serveWebAsset,",
            "    .holder = nullptr,",
            f"    .user_data = const_cast<QcWebAsset*>(&webassets::kAssets[{index}]),",
            "};",
            "",
        ]

    # Wrapped in extern "C", same reason QcWifiWebTransport.hpp's own
    # hand-written HTTP_SERVICE_DEFINE/HTTP_RESOURCE_DEFINE calls are: the
    # macros' STRUCT_SECTION_ITERABLE_ALTERNATE expansion declares extern
    # references to GNU ld's own plain-C section-boundary symbols, which a
    # default C++ (mangled) declaration inside a namespace would not match.
    lines.append('extern "C" {')
    for served, _content_type, _payload in entries:
        name = c_identifier(served)
        lines.append(
            f'HTTP_RESOURCE_DEFINE(qcWebAsset{name}Resource, qcWebService, "{served}", '
            f"&g_webAsset{name}ResourceDetail);"
        )
    lines += ["}", ""]

    write_if_changed(out, "\n".join(lines))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ui-dir", type=Path, required=True, help="path to web/ui")
    parser.add_argument("--out", type=Path, required=True, help="C++ header to write")
    parser.add_argument(
        "--build-id-out", type=Path, required=True, help="C++ header to write the build id to"
    )
    parser.add_argument(
        "--build-id",
        help="the build id to stamp (default: the short git commit of the repository holding --ui-dir)",
    )
    args = parser.parse_args()

    build_id = args.build_id or git_build_id(args.ui_dir)
    if not BUILD_ID_PATTERN.match(build_id):
        raise SystemExit(f"build id {build_id!r} doesn't match docs/api's build pattern")

    entries: list[tuple[str, str, bytes]] = []
    missing: list[str] = []
    for served, content_type in ASSETS:
        path = source_path(args.ui_dir, served)
        if not path.is_file():
            missing.append(str(path))
            continue
        raw = path.read_bytes()
        if served == BUILD_JS:
            raw = stamp_build_js(raw, build_id)
        payload = gzip_bytes(raw)
        entries.append((served, content_type, payload))

    if missing:
        raise SystemExit("missing web UI assets:\n  " + "\n  ".join(missing))

    width = max(len(served) for served, _, _ in entries)
    gz_total = sum(len(payload) for _, _, payload in entries)
    print(f"{'served path'.ljust(width)}  {'gzip -9':>8}")
    for served, _content_type, payload in entries:
        print(f"{served.ljust(width)}  {len(payload):>8}")
    print(f"{'TOTAL'.ljust(width)}  {gz_total:>8}")

    emit_header(entries, args.out)
    emit_build_id_header(build_id, args.build_id_out)
    print(f"\nbuild id {build_id}: {args.out} ({len(entries)} assets, {gz_total} B gzipped)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
